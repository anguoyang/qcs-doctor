"""Tests for the CLI: check / fix end to end."""

import json

import pytest

from qcsdoctor.cli import main


def test_version(capsys):
    with pytest.raises(SystemExit) as exc:
        main(["--version"])
    assert exc.value.code == 0
    assert "qcsdoctor 0.1.0" in capsys.readouterr().out


def test_help(capsys):
    with pytest.raises(SystemExit) as exc:
        main(["--help"])
    assert exc.value.code == 0


def test_check_no_inputs_all_skip(tmp_path, capsys):
    code = main(["check", "--quiet"])
    assert code == 0
    out = capsys.readouterr().out
    assert "HEALTHY" in out or "ATTENTION" in out or "CRITICAL" in out


def test_check_writes_json_and_html(tmp_path):
    json_path = tmp_path / "report.json"
    html_path = tmp_path / "report.html"
    code = main(["check", "--json", str(json_path), "--html", str(html_path)])
    assert code == 0
    report = json.loads(json_path.read_text())
    assert report["schema"] == 1
    assert {item["id"] for item in report["checks"]} == {
        "output_names", "downloader", "tmpdir", "aimet_wheel"}
    assert "Generated by QCS Doctor" in html_path.read_text()


def test_check_output_names_fail_via_cli(tmp_path, capsys):
    params = tmp_path / "params.json"
    params.write_text(json.dumps({"output_names": ["logits"]}), encoding="utf-8")
    code = main(["check", "--compile-params", str(params), "--aimet"])
    assert code == 0  # check reports; it does not fail the process
    out = capsys.readouterr().out
    assert "X output_names" in out
    assert "CRITICAL" in out


def test_fix_dry_run_writes_nothing(tmp_path, capsys):
    params = tmp_path / "params.json"
    params.write_text(json.dumps({"output_names": ["logits"]}), encoding="utf-8")
    code = main(["fix", "--check", "output_names", "--compile-params", str(params),
                 "--workdir", str(tmp_path / "work")])
    assert code == 0
    assert "dry-run" in capsys.readouterr().out
    assert not (tmp_path / "work").exists()


def test_fix_apply_writes_copy(tmp_path, capsys):
    params = tmp_path / "params.json"
    params.write_text(json.dumps({"output_names": ["logits"], "keep": 1}), encoding="utf-8")
    code = main(["fix", "--check", "output_names", "--compile-params", str(params),
                 "--apply", "--workdir", str(tmp_path / "work")])
    assert code == 0
    fixed = json.loads((tmp_path / "work" / "compile-params.fixed.json").read_text())
    assert fixed == {"keep": 1}
    assert "hash-verified" in capsys.readouterr().out


def test_fix_needs_inputs():
    assert main(["fix", "--check", "output_names"]) == 2
    assert main(["fix", "--check", "downloader"]) == 2


def test_unknown_args_rejected():
    with pytest.raises(SystemExit):
        main(["check", "--nope"])
