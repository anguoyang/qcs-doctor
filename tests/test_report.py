"""Tests for the one-page report (schema 1)."""

import json

from qcsdoctor.checks import result
from qcsdoctor.report import build_report, render_html, terminal_report, verdict_line


def _checks():
    return [
        result("a", "A", "pass", "ok"),
        result("b", "B", "warn", "hmm", "watch it"),
        result("c", "C", "fail", "bad", "broken", "fix it"),
        result("d", "D", "skip", None, "no input"),
    ]


def test_verdict_critical_on_fail():
    report = build_report(_checks())
    assert report["verdict"] == "CRITICAL"
    assert report["summary"] == {"pass": 1, "warn": 1, "fail": 1, "skip": 1}
    assert report["schema"] == 1


def test_verdict_attention_and_healthy():
    assert build_report([result("a", "A", "pass", 1)])["verdict"] == "HEALTHY"
    assert build_report([result("a", "A", "warn", 1)])["verdict"] == "ATTENTION"
    assert build_report([])["verdict"] == "HEALTHY"


def test_terminal_and_html_escape():
    report = build_report([result("x", "X <script>", "fail", "<b>", "d&e", evidence="ev")])
    text = terminal_report(report, [])
    assert "X x: <b> (d&e)" in text  # terminal output is raw text
    html = render_html(report)
    assert "<script>" not in html  # HTML output is escaped
    assert "&lt;script&gt;" in html
    assert "Generated by QCS Doctor" in html


def test_verdict_line():
    report = build_report([result("a", "A", "pass", 1)])
    assert verdict_line(report, ["r.json"]) == "HEALTHY | Reports: r.json"
    assert verdict_line(report, []) == "HEALTHY | Reports: none requested"
