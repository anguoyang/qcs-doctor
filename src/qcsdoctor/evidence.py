"""Evidence pack generator (BUILD 3) — scaffold in round 1.

C-level checks (vendor asset / pipeline defects, e.g. check 8: the
unquantized FP32 tensor in the InternVL AOT asset) cannot be fixed
locally. The Doctor's job there is a failure-path record plus an
issue evidence pack that can be filed upstream as-is.

This module is the interface and the pack skeleton only: it writes a
manifest and a markdown template with the facts the caller supplies.
The C-level checks themselves (8, A6) are NOT implemented in round 1
and must not be claimed in the README.
"""

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from . import __version__


def build_evidence_pack(check_id: str, title: str, findings: List[str],
                        evidence_refs: List[str], outdir: Path) -> Dict[str, Any]:
    """Write manifest.json + EVIDENCE_PACK.md into outdir; return manifest."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "schema": 1,
        "tool": "qcs-doctor",
        "tool_version": __version__,
        "check_id": check_id,
        "title": title,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "status": "REPORT-ONLY",
        "findings": list(findings),
        "evidence_refs": list(evidence_refs),
        "note": ("Scaffold pack (round 1): findings and refs are "
                 "caller-supplied; no C-level check fills them yet."),
    }
    (outdir / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    lines = ["# Evidence pack: %s (%s)" % (title, check_id), "",
             "Generated by QCS Doctor %s (REPORT-ONLY)." % __version__, "",
             "## Findings", ""]
    lines += ["- " + finding for finding in findings] or ["- (none recorded)"]
    lines += ["", "## Evidence refs", ""]
    lines += ["- " + ref for ref in evidence_refs] or ["- (none recorded)"]
    lines += ["", "## Status", "",
              "REPORT-ONLY: vendor asset / pipeline defect, not fixable locally.",
              "File upstream with this pack attached.", ""]
    (outdir / "EVIDENCE_PACK.md").write_text("\n".join(lines), encoding="utf-8")
    manifest["files"] = ["manifest.json", "EVIDENCE_PACK.md"]
    return manifest
